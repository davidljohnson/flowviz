/**
 * Generates `.design-sync/entry.ts` (the design system's public barrel) and the
 * `componentSrcMap` block for `.design-sync/config.json`.
 *
 * FlowViz is an app, not a published library: there is no build that emits a
 * `dist/` entry or a `.d.ts` tree, so the converter has nothing authoritative to
 * discover components from. This script enumerates the real exported components
 * from source so both the entry and the map are derived, not hand-typed.
 *
 * Re-run after adding or removing a shared component.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SOURCES = [
  'src/shared/components/Alert/index.tsx',
  'src/shared/components/Button/index.tsx',
  'src/shared/components/Dropdown/index.tsx',
  'src/shared/components/EnhancedDialog/index.tsx',
  'src/shared/components/EnhancedForm/index.tsx',
  'src/shared/components/SearchInput/index.tsx',
  'src/shared/components/SegmentedControl/index.tsx',
  'src/shared/components/Typography/index.tsx',
  'src/shared/components/LoadingIndicator/LoadingIndicator.tsx',
  'src/shared/components/ErrorBoundary/ErrorBoundary.tsx',
  'src/shared/components/ErrorBoundary/ServiceErrorBoundary.tsx',
  'src/shared/components/StreamingProgressBar.tsx',
  'src/shared/components/icons/AssistantMark.tsx',
  'src/features/flow-analysis/components/nodes/ActionNode.tsx',
  'src/features/flow-analysis/components/nodes/ToolNode.tsx',
  'src/features/flow-analysis/components/nodes/MalwareNode.tsx',
  'src/features/flow-analysis/components/nodes/OperatorNode.tsx',
  'src/features/flow-analysis/components/nodes/GenericNode.tsx',
  'src/features/flow-analysis/components/nodes/NodeFactory.tsx',
  'src/features/flow-analysis/components/nodes/shared/NodeCard.tsx',
  'src/features/flow-analysis/components/nodes/shared/NodeHandles.tsx',
  'src/features/flow-analysis/components/nodes/shared/NodeHeader.tsx',
  'src/features/flow-analysis/components/nodes/shared/NodeContent.tsx',
  'src/features/flow-analysis/components/nodes/shared/NoteBadge.tsx',
  'src/shared/theme/ThemeModeProvider.tsx',
];

/**
 * Re-exported third-party providers. Not components — they exist so
 * `cfg.provider` can name them, since it may only reference bundle exports.
 * The node components render ReactFlow `<Handle>`s, which read ReactFlow's
 * store and throw outside its provider.
 */
const PASSTHROUGH = [["ReactFlowProvider", "reactflow"]];

/**
 * Non-component value exports the previews need on `window.FlowViz`. Every cell
 * on a card mounts its own provider but shares one `<html data-theme>`, so a
 * card that shows dark and light side by side can't switch modes by attribute —
 * it applies `themeCssVars(mode)` to the cell's own subtree instead.
 */
const EXTRA_EXPORTS = [['themeCssVars', '../src/shared/theme/flowviz-theme']];

const isComponentName = (n) => /^[A-Z][A-Za-z0-9]*$/.test(n);

/** Named value exports only — `export interface`/`export type` are contracts, not components. */
const namedExports = (src) => {
  const out = new Set();
  const decl = /^export\s+(?:const|let|var|function|class)\s+([A-Za-z0-9_]+)/gm;
  for (const m of src.matchAll(decl)) out.add(m[1]);
  // `export { X as Y }` / `export { X }` — take the exported (outward) name.
  const list = /^export\s*\{([^}]*)\}/gm;
  for (const m of src.matchAll(list)) {
    for (const part of m[1].split(',')) {
      const t = part.trim();
      if (!t || t.startsWith('type ')) continue;
      const as = /\bas\s+([A-Za-z0-9_]+)$/.exec(t);
      out.add(as ? as[1] : t);
    }
  }
  return [...out].filter(isComponentName);
};

/** Default exports are re-exported under the file's own component name. */
const defaultExportName = (src, path) => {
  if (!/^export\s+default\b/m.test(src)) return null;
  const base = path.split('/').pop().replace(/\.tsx$/, '');
  if (base === 'index') return null;
  return isComponentName(base) ? base : null;
};

const map = {};
const lines = [
  '/**',
  ' * The FlowViz design system\'s public surface, as a single entry point.',
  ' *',
  ' * Generated by `.design-sync/gen-entry.mjs` — do not hand-edit. This exists',
  ' * only so the design-sync converter has one module to bundle; the app itself',
  ' * imports these components directly from their own paths.',
  ' */',
  '',
];

for (const path of SOURCES) {
  const src = readFileSync(path, 'utf8');
  const rel = '../' + path.replace(/\.tsx$/, '');
  const named = namedExports(src);
  const def = defaultExportName(src, path);

  if (named.length) {
    lines.push(`export { ${named.join(', ')} } from '${rel}';`);
    for (const n of named) map[n] = path;
  }
  if (def && !named.includes(def)) {
    lines.push(`export { default as ${def} } from '${rel}';`);
    map[def] = path;
  }
}

for (const [name, from] of PASSTHROUGH) lines.push(`export { ${name} } from '${from}';`);
for (const [name, from] of EXTRA_EXPORTS) lines.push(`export { ${name} } from '${from}';`);

lines.push('');
writeFileSync('.design-sync/entry.ts', lines.join('\n'));

const sorted = Object.fromEntries(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync('.design-sync/.componentSrcMap.json', JSON.stringify(sorted, null, 2) + '\n');

console.log(`entry.ts: ${lines.filter((l) => l.startsWith('export')).length} export lines`);
console.log(`components: ${Object.keys(sorted).length}`);
console.log(Object.keys(sorted).join(', '));
